def chapter_files(chapter):
    """The chapter's section files in table-of-contents order."""
    index = os.path.join(ROOT, chapter, 'index.md')
    with open(index, encoding='utf-8') as f:
        toc = re.search(r'```toc\n(.*?)```', f.read(), re.S).group(1)
    names = [l.strip() for l in toc.splitlines() if l.strip() and not l.startswith(':')]
    return [index] + [os.path.join(ROOT, chapter, n + '.md') for n in names]


def generate(out_path):
    from d2lbook import library  # installed for the book build
    blocks = []
    for chapter in CHAPTERS:
        for path in chapter_files(chapter):
            if not os.path.exists(path):
                continue
            for block, _label, _fn in library._save_code(path, tab='pytorch', default_tab='pytorch'):
                # Imports are provided by the header (with browser stand-ins).
                lines = [l for l in block.splitlines()
                         if not re.match(r'(import |from \S+ import )', l)]
                code = '\n'.join(lines).strip()
                if code:
                    blocks.append(f'# {os.path.relpath(path, ROOT)}\n{code}\n')
    for rel, names in EXTRAS:
        for block, _label, _fn in library._save_code(os.path.join(ROOT, rel), tab='pytorch',
                                                     default_tab='pytorch'):
            m = re.search(r'^def (\w+)', block, re.M)
            if m and m.group(1) in names:
                blocks.append(f'# {rel}\n{block.strip()}\n')
    text = HEADER.format(chapters=', '.join(CHAPTERS)) + '\n\n' + '\n\n'.join(blocks) + ALIASES
    compile(text, out_path, 'exec')  # fail the build on a syntax problem
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(text)
    return len(blocks)


if __name__ == '__main__':
    n = generate(sys.argv[1])
    print(f'Wrote {sys.argv[1]} ({n} saved blocks)')
